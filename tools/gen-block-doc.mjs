/* Builds docs/12-week-concurrent-block-v5.md from the vendored V3 source narrative.
 *
 *   node tools/gen-block-doc.mjs        (run after tools/gen-program.mjs)
 *
 * One-shot, like gen-program.mjs. It REFUSES to publish unless what the app runs
 * (src/program.js) agrees with the source plan and its verification:
 *   1. every session's planned minutes and every week's press/vertical/horizontal counts;
 *   2. the row count;
 *   3. the source verification reports zero failures;
 *   4. the resolved coaching amendments are present (A1: no leg curl, 2-set RDL, calves;
 *      A2: week-11 dip back-offs 3×6 @ +47.5; A3: no broad test, no power before the
 *      week-12 Friday tests) and the Friday DB incline bench is present in weeks 1–11;
 *   5. every relative link in the published document resolves.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const rawJson = readFileSync(ROOT + "docs/source/SYNTHESIZED_PRESCRIPTIONS_V3.json", "utf8");
const src = JSON.parse(rawJson);
const jsonHash = createHash("sha256").update(rawJson).digest("hex");
let doc = readFileSync(ROOT + "docs/source/SYNTHESIZED_TRAINING_BLOCK_V3.md", "utf8");
const verif = readFileSync(ROOT + "docs/source/SYNTHESIS_VERIFICATION_V3.md", "utf8");
const { SESSIONS: APP, AUDIT, META, SOURCE } = await import(ROOT + "src/program.js");

const DAY = { sunday: "sun", monday: "mon", wednesday: "wed", friday: "fri" };
const problems = [];

/* ── cross-check 1: minutes and weekly counts ── */
for (const s of src.sessions) {
  const a = APP[s.week]?.[DAY[s.day]];
  if (!a) { problems.push(`missing app session ${s.id}`); continue; }
  if (a.minutes !== s.minutes) problems.push(`${s.id}: app ${a.minutes} min vs source ${s.minutes}`);
}
for (const wa of src.weekly_audit) {
  for (const k of ["press", "vertical", "horizontal"])
    if (AUDIT[wa.week][k] !== wa[k]) problems.push(`week ${wa.week} ${k}: app ${AUDIT[wa.week][k]} vs source ${wa[k]}`);
}

/* ── cross-check 2: row count ── */
const rowCount = src.sessions.reduce((a, s) => a + s.items.length, 0);
if (rowCount !== SOURCE.rows) problems.push(`rows: source ${rowCount} vs app ${SOURCE.rows}`);

/* ── cross-check 3: the source verification must report zero failures ── */
const vm = verif.match(/\*\*(\d+) pass · (\d+) pass with an approved exception · (\d+) fail · (\d+) unknown\*\*/);
if (!vm) problems.push("verification summary line not found");
else if (vm[3] !== "0") problems.push(`source verification reports ${vm[3]} failure(s)`);

/* ── cross-check 4: amendments as resolved, and the incline press ── */
const find = (w, d, id) => APP[w][d].items.find((i) => i.id === id);
for (let w = 1; w <= 12; w++) {
  if (find(w, "mon", "legcurl")) problems.push(`A1: leg curl present in week ${w} (not adopted)`);
  if (!find(w, "fri", "slrdl") || find(w, "fri", "slrdl").sets < 2) problems.push(`A1: single-leg RDL under 2 sets, week ${w}`);
  for (const d of ["mon", "fri"]) if (!APP[w][d].items.some((i) => i.calf)) problems.push(`A1: calves missing ${d} week ${w}`);
  const inc = find(w, "fri", "inclinedb");
  if ((w < 12) !== !!inc) problems.push(`DB incline bench ${inc ? "present" : "missing"} in week ${w}`);
}
const a2 = find(11, "sun", "dipback");
if (!a2 || a2.repsNum !== 6 || a2.load !== 47.5) problems.push("A2: week-11 dip back-offs are not 3×6 @ +47.5");
if (META.targets.broad) problems.push("A3: broad-jump target still present");
if (APP[12].fri.items.some((i) => i.power)) problems.push("A3: power work in front of the week-12 Friday tests");

if (problems.length) {
  console.error("✗ Refusing to publish the program document:\n  - " + problems.join("\n  - "));
  process.exit(1);
}

/* ── rewrite links to the vendored copies (the document lives in docs/, the source in docs/source/) ── */
doc = doc.replace(/\]\((?!https?:|#|source\/)([^)]+)\)/g, (m, p) => `](source/${p})`);
doc = doc.replace(/^# .*\n/, "");   // the section-0 header below replaces the source title

const header = `# Astra Synthesized Concurrent Block — v5.0-syn3

**The program the tracker runs.** Generated by \`tools/gen-program.mjs\` and
\`tools/gen-block-doc.mjs\` from the vendored V3 source in [docs/source/](source/)
(\`SYNTHESIZED_PRESCRIPTIONS_V3.json\`, sha256 \`${jsonHash.slice(0, 16)}…\`). **Ready for
review, not approved** — the source says so, and so should anyone citing it. Every load, time
and outcome is planned, not demonstrated.

## 0. What the app runs, and how it got here

- **Dates:** week 1 starts Sunday, 27 September 2026; week 12 is 13–19 December; the optional
  week-13 makeup for deferred tests is **Saturday, 26 December**.
- **Time:** strength sessions are a **hard 75-minute limit** (5-minute delay reserve
  included). Wednesday impact is a hard 15 minutes; Friday impact a ~30-minute target. Travel
  is not budgeted.
- **Goals:** OHP ${META.targets.ohp} at ${META.targetStandard.ohp}; dip ${META.targets.dip} and
  pull-up ${META.targets.pullup} at ${META.targetStandard.dip}; squat and deadlift maintained;
  plyometric capacity progressively higher (no broad-jump test).
- **Coaching amendments A1–A3** (applied to the previous block in the app on 22 Sep) are
  carried in the V3 source itself, as Brian resolved them on 24 Sep:
  - **A1** — calves on both lower days (≥3 varied sets) and a 2-set Friday single-leg RDL are
    in; the Monday lying leg curl is **not** (Brian asked to avoid machines). Watch item for
    the faster sprint weeks 8–11.
  - **A2** — week-11 Sunday dip back-offs are 3×6 @ +47.5, so the +50×6 test is the same 2.5 lb
    step as every other.
  - **A3** — no broad-jump measurement, and week-12 Friday carries no power work and no
    kettlebell complex (approved exception E11).
- **Added 24 Sep:** Friday dumbbell incline bench (2×8–10, supersetted with the single-leg RDL;
  none in week 12), with a fourth Sunday row set to hold press:pull at 1.25.
- **The two-set rule:** no exercise is ever done for a single set (target tests excepted); a
  cut skips a whole optional exercise instead.
- **Weekly changes** are made by hand in \`src/program.js\` against
  [autoregulation-criteria.md](autoregulation-criteria.md); \`test.mjs\` guards the rails.

Cross-checked at generation: ${src.sessions.length} sessions and ${rowCount} rows agree with the app;
every week's press/vertical/horizontal count agrees; the source verification reports
${vm[1]} pass, ${vm[2]} approved exceptions and 0 failures.

---

`;
doc = header + doc;
writeFileSync(ROOT + "docs/12-week-concurrent-block-v5.md", doc);

/* ── every relative link must resolve ── */
const base = ROOT + "docs/";
const broken = [...doc.matchAll(/\]\((?!https?:|#)([^)#]+)(?:#[^)]*)?\)/g)]
  .map((m) => m[1])
  .filter((p) => !existsSync(resolve(dirname(base + "x"), p)));
if (broken.length) {
  console.error("✗ Broken relative links:\n  - " + [...new Set(broken)].join("\n  - "));
  process.exit(1);
}
console.log(`✓ docs/12-week-concurrent-block-v5.md written — ${src.sessions.length} sessions, ${rowCount} rows cross-checked, amendments A1–A3 resolved, incline present, 0 broken links`);
